import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const migrations = [
    '002_damage_reports.sql',
    '003_daily_checklist.sql',
    '004_remaining_modules.sql',
    '20261125132304_store_operations_security.sql',
    '20261125132739_shelf_inspection_workflow.sql',
    '20261125133146_damage_reporting_workflow.sql',
    '20261125133414_tester_management_workflow.sql',
    '20261125133455_daily_checklist_workflow.sql',
    '20261125133757_task_management_workflow.sql',
    '20261125133949_store_audits_workflow.sql',
    '20261125134046_incidents_and_restocking_workflow.sql',
    '20261125134427_store_operations_notifications_reports.sql',
];

// Keep a single transaction: legacy policies must never become visible halfway
// through installation. Migration files remain the source of truth.
const sections = migrations.map(name => {
    let sql = readFileSync(new URL(`supabase/migrations/${name}`, root), 'utf8').trim();
    if (name.startsWith('2026')) {
        if (!sql.startsWith('BEGIN;') || !sql.endsWith('COMMIT;')) {
            throw new Error(`${name} must have one outer BEGIN/COMMIT transaction.`);
        }
        sql = sql.slice('BEGIN;'.length, -'COMMIT;'.length).trim();
    }
    if (/^\s*(?:BEGIN|COMMIT|ROLLBACK);\s*$/m.test(sql)) {
        throw new Error(`Unexpected transaction boundary inside ${name}.`);
    }
    return `-- Source: supabase/migrations/${name}\n${sql}`;
});

const preflight = `-- Generated by npm run store-ops:sql. Do not edit this file directly.
-- Run this ENTIRE file once in Supabase SQL Editor as the postgres role.
-- Creates missing operations base tables, then applies all operations repairs.
-- Existing records are retained. No attendance migrations or scheduler are run.
-- Requires the existing attendance notification/device migration.
BEGIN;
SET LOCAL search_path = public, extensions;
DO $install_prerequisites$
DECLARE missing_tables text;
BEGIN
 SELECT string_agg(name, ', ' ORDER BY name) INTO missing_tables
 FROM unnest(ARRAY['public.profiles','public.stores','storage.objects','storage.buckets',
  'public.attendance_notification_devices','hrm_private.attendance_notification_keys']) AS required(name)
 WHERE to_regclass(name) IS NULL;
 IF missing_tables IS NOT NULL THEN
  RAISE EXCEPTION USING MESSAGE='Required existing application tables are missing: ' || missing_tables,
   HINT='Use the intended Supabase project. For missing attendance notification tables, apply the existing attendance migrations through 20261124094512_attendance_reminders.sql first.';
 END IF;
 IF to_regprocedure('store_ops_private.guard_record()') IS NOT NULL
    OR to_regclass('public.checklist_template_items') IS NOT NULL
    OR to_regclass('public.store_operation_events') IS NOT NULL THEN
  RAISE EXCEPTION USING MESSAGE='Store Operations repair migrations are already installed or partially installed.',
   HINT='Apply only the remaining versioned migrations in order. This recovery bundle is for an installation with no successfully applied Store Operations repair migrations.';
 END IF;
END $install_prerequisites$;
`;

const output = new URL('supabase/deployment/store_operations_install.sql', root);
writeFileSync(output, `${preflight}\n${sections.join('\n\n')}\n\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\nSELECT 'Store Operations installation complete' AS result;\n`);
console.log(`Wrote ${fileURLToPath(output)} (${migrations.length} ordered migrations, one transaction).`);
